package io.oryxos.core.memory;

/**
 * 记忆分类 —— 决定一条记忆写进哪个区块、以及它是否参与检索与截断。
 *
 * <p>这套分层借自 MemGPT 的 core memory 思想（见 {@code docs/class/第21节}）：
 * 有一小块信息要"永远在场"，其余大量事实按需检索。</p>
 */
public enum MemoryScope {

    /**
     * 核心记忆：始终在场，小而精。
     *
     * <p>典型内容：用户是谁、项目背景、关键约束偏好。每次都完整拼进上下文，
     * <b>不检索、不截断</b>。</p>
     */
    CORE,

    /**
     * 归档记忆：长期积累的事实与历史。
     *
     * <p>按需检索（关键词）、按阈值截断（只保留最近的部分）。未指定分类时的默认去向。</p>
     */
    ARCHIVAL
}
